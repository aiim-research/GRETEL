#!/usr/bin/env python3
"""Plain-LBS ablations on PROTEINS (10 folds): which of the search-policy changes behind the selector
skeleton matter, with the thesis implementation itself and parameters only.

The selector skeleton with uniform proposals (``dce-lcls-sel-random``) is the ablation "every change, no
model". These arms isolate the two biggest changes on the thesis implementation (``local_search.py``):

    dce-lcls-single       removal levels one edge apart (``max_neigh`` 100: step = int(|S| / 100) + 1 = 1 up
                          to |S| 99), so single-edge removals are tried at every |S|; the thesis setting
                          (``max_neigh`` 20) skips them from |S| 20 on (step 2, 3, ...)
    dce-lcls-stop         the search ends after the first outer iteration without improvement
                          (``stop_after_failed_iteration``, the pseudocode's "repeat until no strategy
                          accepts"); the thesis setting retries up to ``max_runtime`` 20 times
    dce-lcls-single-stop  both

Everything else is the thesis config of ``proteins-sel/dce/dce-lcls`` (strict budget 10000, seed 0, the
generator cache). Queue: ``docs/selector/SERVER_PROTEINS_LBS_ABLATIONS.md``.

    python scripts/gen_lbs_ablations.py
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TREE = REPO / "lab/config/generate_minimize/proteins-sel/dce"
ARMS = {
    "dce-lcls-single": {"max_neigh": 100},
    "dce-lcls-stop": {"stop_after_failed_iteration": True},
    "dce-lcls-single-stop": {"max_neigh": 100, "stop_after_failed_iteration": True},
}


def main() -> int:
    queue = []
    for arm, extra in ARMS.items():
        for fold in range(10):
            conf = json.load(open(TREE / "dce-lcls" / f"generate_minimize{fold}.jsonc"))
            conf["experiment"]["scope"] = "proteins-sel_" + arm.replace("dce-lcls", "dce_lcls", 1)
            par = conf["doe-triplets"][0]["explainer"]["parameters"]["minimizer"]["parameters"]
            assert par["max_neigh"] == 20 and par["strict_budget"] and par["max_oracle_calls"] == 10000, par
            par.update(extra)
            out = TREE / arm / f"generate_minimize{fold}.jsonc"
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(json.dumps(conf, indent=4) + "\n")
            queue.append(str(out.relative_to(REPO)))
    q = REPO / "docs/selector/SERVER_PROTEINS_LBS_ABLATIONS.md"
    q.write_text("# Plain-LBS ablations on PROTEINS, 10 folds: single-edge removal level, stop after the first failed "
                 "iteration, both\n\nGenerated by `scripts/gen_lbs_ablations.py` (its docstring describes the arms). "
                 "Submit with `launchers/slurm_submit.sh -p normal -m 10 docs/selector/SERVER_PROTEINS_LBS_ABLATIONS.md`.\n\n"
                 + "\n".join(f"- [ ] {c}" for c in queue) + "\n")
    print(f"{len(queue)} configs, queue {q.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
