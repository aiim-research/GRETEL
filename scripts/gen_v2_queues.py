#!/usr/bin/env python3
"""Queues of the protocol v2 sondeo on the Slurm server: fold 0 of the first paper's and the selector paper's cells.

The sondeo checks that the first paper's comparisons run without padding and gives their first v2 numbers
(docs/v2/RUNS.md is the tutorial). Two phases, as in the v1 rerun: phase A holds the generator-only runs
(``*-dummy``), which fill the shared generator cache (generation stays decoupled: one seed per instance and
fold for every minimizer); phase B every minimizer, BLS-F included, starting from those seeds. Submit both
with ``launchers/slurm_submit.sh -c`` so B starts when A has ended. The selector paper's cells (``*-sel``):
``SONDEO_SEL_A`` holds bls_v0, bls_v1 and the untrained control on fold 0 and the collections of fold 1 (the
training data of the ``-f1`` checkpoint, which serves fold 0); after it, the pretraining job
(``launchers/slurm_pretrain.sh --v2``) and ``SONDEO_SEL_B``, selector_v1 on fold 0. The full fleets (phases 1 and
2 of docs/v2/RUNS.md) are generated once this sondeo gives the v2 hours per config. ``SONDEO_SEL_F_A`` and
``SONDEO_SEL_F_B`` are the same two stages for the selector arms with BLS-F substitutions (``<arm>-f``), with the
pretraining job ``launchers/slurm_pretrain.sh --v2 --features`` between them.

    python scripts/gen_v2_queues.py
"""
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TREE = REPO / "lab/config/v2/generate_minimize"
DOCS = REPO / "docs/v2"


def main() -> int:
    configs = sorted(str(p.relative_to(REPO)) for p in TREE.glob("*/*/*/generate_minimize0.jsonc")
                     if not p.parts[-4].endswith("-sel"))
    phase_a = [c for c in configs if Path(c).parts[-2].endswith("-dummy")]
    phase_b = [c for c in configs if c not in phase_a]
    for name, items, what in (("SONDEO_A.md", phase_a, "phase A, the generators alone (fill the generator cache)"),
                              ("SONDEO_B.md", phase_b, "phase B, every minimizer from the cached seeds")):
        lines = [f"# Protocol v2 sondeo, {what}: {len(items)} configs, fold 0", "",
                 "Generated by `scripts/gen_v2_queues.py`. `launchers/slurm_submit.sh -p normal -m 10 -c "
                 "docs/v2/SONDEO_A.md docs/v2/SONDEO_B.md` (docs/v2/RUNS.md).", ""]
        lines += [f"- [ ] {c}" for c in items]
        (DOCS / name).write_text("\n".join(lines) + "\n")
    sel = sorted(str(p.relative_to(REPO)) for p in TREE.glob("*-sel/dce/*/generate_minimize*.jsonc"))
    sel_a = [c for c in sel if (Path(c).parts[-2] in ("dce-lcls-v0", "dce-lcls-v1", "dce-lcls-sel-v1-untrained")
                                and c.endswith("generate_minimize0.jsonc"))
             or (Path(c).parts[-2] == "dce-lcls-collect2" and c.endswith("generate_minimize1.jsonc"))]
    sel_b = [c for c in sel if Path(c).parts[-2] == "dce-lcls-sel-v1" and c.endswith("generate_minimize0.jsonc")]
    for name, items, what, how in (
            ("SONDEO_SEL_A.md", sel_a, "selector cells: bls_v0, bls_v1 and the untrained control on fold 0, the collections of fold 1",
             "launchers/slurm_submit.sh -p normal -m 10 docs/v2/SONDEO_SEL_A.md"),
            ("SONDEO_SEL_B.md", sel_b, "selector_v1 on fold 0 (needs the -f1 checkpoints of the pretraining job)",
             "launchers/slurm_submit.sh -p normal -m 10 docs/v2/SONDEO_SEL_B.md")):
        lines = [f"# Protocol v2 sondeo, {what}: {len(items)} configs", "",
                 f"Generated by `scripts/gen_v2_queues.py`. `{how}` (docs/v2/RUNS.md).", ""]
        lines += [f"- [ ] {c}" for c in items]
        (DOCS / name).write_text("\n".join(lines) + "\n")
    # The fleet (2026-11-08): DCEM only, every selector cell but COLORS-3 (its oracle is broken), folds 0 to 9 in
    # fold order. A: DCEM alone (fills the seed cache). B: the collections-F of folds 1 and 2 and every arm that
    # needs no checkpoint: OBS, RHC, bls_v0 (paper 1's BLS), bls_v1-F, the untrained control-F. Then the
    # pretraining (--v2 --features --dcem) and C: selector_v1-F. Paper 1's main table is the DCEM alone, bls_v0
    # and OBS rows of the six paper-1 datasets among these cells; its ablations and DCE are not rerun.
    fleet = sorted(str(p.relative_to(REPO)) for p in TREE.glob("*-sel/dcm/*/generate_minimize*.jsonc")
                   if not p.parts[-4].startswith("colors-3") and p.parts[-2] != "dcm-rhc-b")
    fleet.sort(key=lambda c: (int(Path(c).stem.removeprefix("generate_minimize")), c))
    var = lambda c: Path(c).parts[-2]
    f_a = [c for c in fleet if var(c) == "dcm-dummy"]
    f_c = [c for c in fleet if var(c) == "dcm-lcls-sel-v1-f"]
    f_b = [c for c in fleet if c not in f_a and c not in f_c]
    cells = sorted({Path(c).parts[-4].removesuffix("-sel") for c in fleet})
    for name, items, what in (
            ("FLEET_A.md", f_a, "DCEM alone in every cell, folds 0 to 9 (fills the seed cache)"),
            ("FLEET_B.md", f_b, "the collections-F of folds 1 and 2, OBS, RHC, bls_v0, bls_v1-F and the untrained "
                                "control-F, folds 0 to 9"),
            ("FLEET_C.md", f_c, "selector_v1-F, folds 0 to 9 (needs the sel2fm-pre checkpoints)")):
        lines = [f"# Protocol v2 fleet, {what}: {len(items)} configs", "",
                 "Generated by `scripts/gen_v2_queues.py` (docs/v2/RUNS.md).", ""]
        lines += [f"- [ ] {c}" for c in items]
        (DOCS / name).write_text("\n".join(lines) + "\n")
    (DOCS / "FLEET_CELLS.txt").write_text(" ".join(cells) + "\n")
    # Run last (2026-11-09): RHC at bls_v1-F's budget per cell (docs/v2/RHC_BUDGET.json), for the expansion.
    rhc_b = sorted(str(p.relative_to(REPO)) for p in TREE.glob("*-sel/dcm/dcm-rhc-b/generate_minimize*.jsonc")
                   if not p.parts[-4].startswith("colors-3"))
    rhc_b.sort(key=lambda c: (int(Path(c).stem.removeprefix("generate_minimize")), c))
    (DOCS / "LAST_RHC_B.md").write_text("\n".join(
        [f"# Protocol v2, run last: RHC at bls_v1-F's budget per cell, folds 0 to 9: {len(rhc_b)} configs", "",
         "Generated by `scripts/gen_v2_queues.py` (docs/v2/RUNS.md). Needs the DCEM seeds of FLEET_A.", ""]
        + [f"- [ ] {c}" for c in rhc_b]) + "\n")
    print(f"fleet: A {len(f_a)}, B {len(f_b)}, C {len(f_c)}, {len(cells)} cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
