import random

import networkx as nx
import numpy as np

from src.dataset.generators.base import Generator
from src.dataset.instances.graph import GraphInstance


class TriangleThreshold(Generator):
    """Holme-Kim graphs (``nx.powerlaw_cluster_graph``: ``num_nodes`` nodes, ``edges_per_node`` edges per
    new node, so every graph has about the same number of edges) whose triad-formation probability is
    drawn at random, which spreads the number of triangles widely. Label 1 for graphs with at least
    ``min_triangles_class1`` triangles, label 0 for at most ``max_triangles_class0``; graphs in between are
    rejected, so a counterfactual has to create or destroy many triangles (``TriangleCountOracle`` puts
    its threshold in the gap). Classes alternate, so they are balanced. Deterministic (``seed``, default
    0) and generated once per dataset object, like the fixed Tree-Cycles generators.
    """

    def init(self):
        p = self.local_config['parameters']
        self.num_instances = p['num_instances']
        self.num_nodes = p['num_nodes']
        self.edges_per_node = p['edges_per_node']
        self.max_triangles_class0 = p['max_triangles_class0']
        self.min_triangles_class1 = p['min_triangles_class1']
        self.seed = p.get('seed', 0)
        self.generate_dataset()

    def check_configuration(self):
        super().check_configuration()
        p = self.local_config['parameters']
        for key in ('num_instances', 'num_nodes', 'edges_per_node', 'max_triangles_class0', 'min_triangles_class1'):
            if key not in p:
                raise ValueError(f"TriangleThreshold needs {key}")
        if p['max_triangles_class0'] >= p['min_triangles_class1']:
            raise ValueError("max_triangles_class0 must be below min_triangles_class1")

    def generate_dataset(self):
        if self.dataset.instances:   # already generated by the constructor (Dataset.read calls init again)
            return
        rng = random.Random(self.seed)
        for i in range(self.num_instances):
            label = i % 2
            while True:
                g = nx.powerlaw_cluster_graph(self.num_nodes, self.edges_per_node, rng.random(),
                                              seed=rng.randrange(2 ** 31))
                t = sum(nx.triangles(g).values()) // 3
                if (label == 1 and t >= self.min_triangles_class1) or (label == 0 and t <= self.max_triangles_class0):
                    break
            self.dataset.instances.append(GraphInstance(id=i, data=nx.to_numpy_array(g), label=label))
            self.context.logger.info(f"Generated instance with id:{i} ({t} triangles)")
