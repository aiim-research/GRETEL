import random

import networkx as nx
import numpy as np

from src.dataset.generators.base import Generator
from src.dataset.instances.graph import GraphInstance


class TreeCyclesRand(Generator):
    """Random trees (label 0) and random trees with cycles of random sizes attached (label 1).

    Generation is deterministic: every random draw comes from local generators seeded with the optional
    ``seed`` parameter (default 0; read without being written back into the config, so the dataset
    hashes do not change), and ``generate_dataset`` runs once per dataset object. ``Dataset.read`` calls
    ``init`` on a generator whose constructor has already generated the instances: without the guard
    every instance was appended twice with the same id, and every process drew different graphs.
    """

    def init(self):
        self.num_instances = self.local_config['parameters']['num_instances']
        self.num_nodes_per_instance = self.local_config['parameters']['num_nodes_per_instance']
        self.ratio_nodes_in_cycles = self.local_config['parameters']['ratio_nodes_in_cycles']
        self.seed = self.local_config['parameters'].get('seed', 0)
        self.generate_dataset()

    def check_configuration(self):
        super().check_configuration
        local_config=self.local_config

        # set defaults
        local_config['parameters']['num_instances'] = local_config['parameters'].get('num_instances', 1000)
        local_config['parameters']['num_nodes_per_instance'] = local_config['parameters'].get('num_nodes_per_instance', 300)
        local_config['parameters']['ratio_nodes_in_cycles'] = local_config['parameters'].get('ratio_nodes_in_cycles', 0.3)

    def generate_dataset(self):
        if self.dataset.instances:   # already generated by the constructor (see the class docstring)
            return
        rng = np.random.RandomState(self.seed)
        tree_rng = random.Random(self.seed)

        for i in range(self.num_instances):
            # Randomly determine if the graph is going to contain cycles or just be a tree
            has_cycles = rng.randint(0, 2) # 2 excluded
            # If the graph will contain cycles
            if(has_cycles):
                cycles = []
                budget = int( self.ratio_nodes_in_cycles * self.num_nodes_per_instance )
                left = self.num_nodes_per_instance - budget

                while budget > 2:
                    num_nodes = rng.randint(3, budget + 1)
                    cycles.append(nx.cycle_graph(num_nodes))
                    budget -= num_nodes

                left += budget
                tc_graph = self._join_graphs_as_adj(nx.random_tree(n=left, seed=tree_rng), cycles, rng)

                self.dataset.instances.append(GraphInstance(id=i, data=tc_graph, label=1))
            else:
                # Generating a random tree containing all the nodes of the instance
                t_graph = nx.random_tree(n=self.num_nodes_per_instance, seed=tree_rng)
                self.dataset.instances.append(GraphInstance(id=i, data=nx.to_numpy_array(t_graph), label=0))

            self.context.logger.info("Generated instance with id:"+str(i))

    def _join_graphs_as_adj(self, base, others, rng):
        Ab = nx.to_numpy_array(base)
        A = Ab
        for other in others:
            Ao = nx.to_numpy_array(other)
            t_node = rng.randint(0, len(Ab))
            s_node = len(A) + rng.randint(0, len(Ao))
            A = np.block([[A,np.zeros((len(A),len(Ao)))],[np.zeros((len(Ao),len(A))), Ao]])
            A[t_node,s_node]=1
            A[s_node,t_node]=1

        return A
